#!/bin/bash
# THE CLAUDE.AI TRIAL (2026-10-26): a fresh trial store, the memory server over
# HTTP (src/adapters/remote/), a tunnel to it, and the URL printed once.
#
#   trial.sh start [--local] [--dry-run] [--dir DIR]   serve; Ctrl-C stops it all
#   trial.sh check [--dir DIR]                         start --local, prove the door, stop
#   trial.sh report [--dir DIR]                        what the call log says, per connection
#   trial.sh night LOCAL_URL [--dry-run] [--dir DIR]   optional: run a night by hand (claude -p)
#
# DIR defaults to ~/counterparts-trials/claude-ai. It is never ~/.counterparts:
# the script and the server both refuse the owner's live stores. The secret
# path is generated by the server per run and printed once, here; it is not
# written to any file. Stopping the server (Ctrl-C) kills the tunnel, and the
# URL dies with them.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../../.." && pwd)"
BUN="${BUN:-$(command -v bun || echo "$HOME/.bun/bin/bun")}"
SERVER="$REPO/src/adapters/remote/bin/serve-http.ts"
BUNFIG="$REPO/src/adapters/empty-bunfig.toml"

cmd="${1:-}"
[ $# -gt 0 ] && shift
DIR="$HOME/counterparts-trials/claude-ai"
LOCAL=0
DRY=0
NIGHT_URL=""
while [ $# -gt 0 ]; do
  case "$1" in
    --dir) DIR="$2"; shift 2 ;;
    --local) LOCAL=1; shift ;;
    --dry-run) DRY=1; shift ;;
    http://127.0.0.1:*) NIGHT_URL="$1"; shift ;;
    *) echo "trial.sh: unknown argument: $1" >&2; exit 2 ;;
  esac
done

case "$DIR" in /*) ;; *) DIR="$(pwd)/$DIR" ;; esac
for live in "$HOME/.counterparts" "$HOME/.bansai" "$HOME/.claude-engram"; do
  case "$DIR/" in "$live/"*) echo "trial.sh: refused: $DIR is inside $live, a live store. Use a trial directory of its own." >&2; exit 1 ;; esac
done

# The prompt a night runs on: the Cowork scheduled task's text, and `night`'s.
NIGHT_PROMPT='Do tonight'"'"'s memory work with the counterparts-trial tools, on your own, without asking me anything. First call wake once and keep the session id it returns. Then call the dream tool with phase "launch" and that session id, and follow the prompt it returns yourself, here, step by step, through every call it names (day'"'"'s end, the dream, then the reflection), passing the same session id each time. If a tool refuses, note its reason and go on to the next step. End with a short list of the steps, each marked done or with the reason it stopped. Do not quote any memory in that list.'

fresh_store() {
  mkdir -p "$DIR"
  chmod 700 "$DIR"
  if [ ! -f "$DIR/config.json" ]; then
    printf '{\n  "dataDir": "%s/store",\n  "snapshots": { "dir": "%s/snapshots" }\n}\n' "$DIR" "$DIR" > "$DIR/config.json"
    echo "trial.sh: new trial store at $DIR/store" >&2
  fi
  if [ ! -f "$DIR/canary.txt" ]; then
    local adj=(Amber Cobalt Saffron Juniper Marrow Thistle Quill Larch Pewter Indigo Russet Vellum)
    local noun=(Harrow Quillmere Fennwick Ostrel Brackenlow Sablewyn Tarnhollow Mirelock Wrenfold Calder)
    local a n
    a=$(( $(od -An -N2 -tu2 /dev/urandom | tr -d ' ') % ${#adj[@]} ))
    n=$(( $(od -An -N2 -tu2 /dev/urandom | tr -d ' ') % ${#noun[@]} ))
    printf "Canary for this trial: the person's imaginary lighthouse is called %s %s." "${noun[$n]}" "${adj[$a]}" > "$DIR/canary.txt"
  fi
}

RUN=""
SERVER_PID=""
TUNNEL_PID=""
AWAKE_PID=""
cleanup() {
  [ -n "$TUNNEL_PID" ] && kill "$TUNNEL_PID" 2>/dev/null || true
  [ -n "$SERVER_PID" ] && kill -TERM "$SERVER_PID" 2>/dev/null || true
  [ -n "$AWAKE_PID" ] && kill "$AWAKE_PID" 2>/dev/null || true
  [ -n "$SERVER_PID" ] && wait "$SERVER_PID" 2>/dev/null || true
  [ -n "$RUN" ] && rm -rf "$RUN"
  rm -f "$DIR/server.pid"
}

start_server() {
  fresh_store
  if [ -f "$DIR/server.pid" ] && kill -0 "$(cat "$DIR/server.pid")" 2>/dev/null; then
    echo "trial.sh: a trial server is already running (pid $(cat "$DIR/server.pid")). Stop it first." >&2
    exit 1
  fi
  RUN="$(mktemp -d)"
  chmod 700 "$RUN"
  mkfifo "$RUN/out"
  trap cleanup EXIT
  trap 'exit 0' INT TERM HUP
  # Nothing of a Claude Code session's environment, and the explicit-dir guard on.
  env -u CLAUDE_PROJECT_DIR -u CLAUDECODE -u CLAUDE_CODE_ENTRYPOINT -u COUNTERPARTS_CONFIG -u COUNTERPARTS_DATA_DIR \
    COUNTERPARTS_REQUIRE_EXPLICIT_DIR=1 \
    "$BUN" --no-env-file "--config=$BUNFIG" "$SERVER" \
    --dir "$DIR/store" --config "$DIR/config.json" --call-log "$DIR/calls.jsonl" \
    --canary "$(cat "$DIR/canary.txt")" \
    > "$RUN/out" 2>> "$DIR/server.log" &
  SERVER_PID=$!
  echo "$SERVER_PID" > "$DIR/server.pid"
  exec 3< "$RUN/out"
  local line=""
  if ! read -r -t 60 line <&3 || [ "${line#url }" = "$line" ]; then
    echo "trial.sh: the server did not start; see $DIR/server.log" >&2
    tail -5 "$DIR/server.log" >&2 || true
    exit 1
  fi
  LOCAL_URL="${line#url }"
  PORT="${LOCAL_URL#http://127.0.0.1:}"
  PORT="${PORT%%/*}"
  SECRET="${LOCAL_URL##*/}"
}

check_door() {
  local base="http://127.0.0.1:$PORT"
  local init
  init=$(curl -s -X POST "$LOCAL_URL" -H 'content-type: application/json' \
    -d '{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-06-18","capabilities":{},"clientInfo":{"name":"trial-check","version":"0"}}}')
  case "$init" in *'"serverInfo":{"name":"counterparts"'*) echo "check: initialize answered" ;; *) echo "check: initialize FAILED: $init" >&2; return 1 ;; esac
  case "$init" in *"$(cat "$DIR/canary.txt")"*) echo "check: the canary is in instructions" ;; *) echo "check: canary missing" >&2; return 1 ;; esac
  local list
  list=$(curl -s -X POST "$LOCAL_URL" -H 'content-type: application/json' -d '{"jsonrpc":"2.0","id":2,"method":"tools/list"}')
  case "$list" in *'"name":"wake"'*) echo "check: tools/list offers wake" ;; *) echo "check: tools/list FAILED" >&2; return 1 ;; esac
  local wrong
  wrong=$(curl -s -o /dev/null -w '%{http_code}' -X POST "$base/" -d '{}')
  [ "$wrong" = "404" ] && echo "check: a wrong path is 404" || { echo "check: wrong path gave $wrong" >&2; return 1; }
  local bound
  bound=$(lsof -nP -a -p "$SERVER_PID" -iTCP -sTCP:LISTEN 2>/dev/null | awk 'NR>1{print $9}' | sort -u | tr '\n' ' ')
  echo "check: listening on ${bound:-?(lsof unavailable)}"
  case "$bound" in *"*:"*|*"0.0.0.0"*) echo "check: NOT loopback-only" >&2; return 1 ;; esac
}

case "$cmd" in
  start)
    if [ "$DRY" = 1 ] && [ "$LOCAL" = 0 ]; then
      fresh_store
      echo "dry run: would start the server on 127.0.0.1 (a free port), then:"
      echo "  cloudflared tunnel --no-autoupdate --loglevel info --url http://127.0.0.1:<port>"
      echo "and print https://<name>.trycloudflare.com/<secret> once."
      command -v cloudflared >/dev/null || echo "cloudflared is not installed: brew install cloudflared"
      exit 0
    fi
    start_server
    if command -v caffeinate >/dev/null; then caffeinate -i -w "$SERVER_PID" & AWAKE_PID=$!; fi
    if [ "$LOCAL" = 1 ]; then
      echo
      echo "Local only (no tunnel). This URL works on this Mac alone:"
      echo "$LOCAL_URL"
    else
      if ! command -v cloudflared >/dev/null; then
        echo "trial.sh: cloudflared is not installed. Run: brew install cloudflared" >&2
        exit 1
      fi
      : > "$DIR/tunnel.log"
      # `info` pinned: at `debug` cloudflared logs every request URL, secret included.
      cloudflared tunnel --no-autoupdate --loglevel info --url "http://127.0.0.1:$PORT" >> "$DIR/tunnel.log" 2>&1 &
      TUNNEL_PID=$!
      HOST=""
      for _ in $(seq 1 60); do
        HOST=$(grep -Eo 'https://[a-z0-9-]+\.trycloudflare\.com' "$DIR/tunnel.log" | head -1 || true)
        [ -n "$HOST" ] && break
        kill -0 "$TUNNEL_PID" 2>/dev/null || break
        sleep 1
      done
      if [ -z "$HOST" ]; then
        echo "trial.sh: the tunnel did not come up; see $DIR/tunnel.log" >&2
        exit 1
      fi
      echo
      echo "The connector URL (paste it into claude.ai; it dies when this stops):"
      echo "$HOST/$SECRET"
      echo
      echo "For a night by hand, in another terminal, while this runs:"
      echo "$HERE/trial.sh night $LOCAL_URL"
    fi
    echo
    echo "Canary question for a cold chat: What is my imaginary lighthouse called?"
    echo "Running. Ctrl-C stops the server and the tunnel."
    wait "$SERVER_PID" || true
    ;;
  check)
    LOCAL=1
    start_server
    check_door
    echo "check: passed; stopping."
    ;;
  report)
    exec "$BUN" --no-env-file "--config=$BUNFIG" "$HERE/report.ts" "$DIR/calls.jsonl"
    ;;
  night)
    if [ -z "$NIGHT_URL" ]; then echo "trial.sh night: pass the local URL the start command printed (http://127.0.0.1:...)" >&2; exit 2; fi
    MCP=$(printf '{"mcpServers":{"counterparts-trial":{"type":"http","url":"%s"}}}' "$NIGHT_URL")
    # A night on the trial store only: no hooks (so the live install's hooks
    # never see this session), no other MCP server, no claude.ai connectors,
    # no built-in tools, only the trial's tools allowed; run in the trial dir.
    set -- claude -p --settings '{"disableAllHooks":true}' --strict-mcp-config --mcp-config "$MCP" \
      --tools "" --allowedTools "mcp__counterparts-trial__*" --permission-mode default --no-session-persistence \
      --max-turns 80
    if [ "$DRY" = 1 ]; then
      echo "dry run, from $DIR, with ENABLE_CLAUDEAI_MCP_SERVERS=false:"
      printf '%q ' "$@" | sed "s|$(printf '%q' "$NIGHT_URL" | sed 's/[&|]/\\&/g')|<local url>|"
      echo '<the night prompt on stdin>'
      exit 0
    fi
    cd "$DIR"
    printf '%s' "$NIGHT_PROMPT" | ENABLE_CLAUDEAI_MCP_SERVERS=false "$@"
    ;;
  prompt)
    printf '%s\n' "$NIGHT_PROMPT"
    ;;
  *)
    sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'
    exit 2
    ;;
esac
